/**
 * Converte o nome da faixa do aluno em um número de ordenação hierárquico (1 a 13).
 * Garante que faixas compostas (ex: Azul Ponta Amarela) sejam resolvidas com precisão.
 */
export function getBeltOrder(beltName: string = ''): number {
  const normalized = beltName.toLowerCase().trim();
  if (!normalized) return 1;

  if (normalized.includes('preta') || normalized.includes('dan')) return 13;
  if (normalized.includes('marrom')) return 12;
  if (normalized.includes('roxa')) return 11;
  if (normalized.includes('verde')) return 10;
  
  if (normalized.includes('laranja')) {
    if (normalized.includes('amarela')) return 8; // Amarela Ponta Laranja
    return 9; // Laranja pura
  }
  
  if (normalized.includes('amarela')) {
    if (normalized.includes('azul')) return 6; // Azul Ponta Amarela
    return 7; // Amarela pura
  }
  
  if (normalized.includes('azul')) {
    if (normalized.includes('cinza')) return 4; // Cinza Ponta Azul
    return 5; // Azul pura
  }
  
  if (normalized.includes('cinza')) {
    if (normalized.includes('branca')) return 2; // Branca Ponta Cinza
    return 3; // Cinza pura
  }
  
  return 1; // Branca
}

/**
 * Verifica se uma técnica é exigida para o aluno com base na regra cumulativa:
 * Um judoca deve dominar o conteúdo da sua faixa atual E de todas as faixas anteriores.
 */
export function isTechniqueRequiredForBelt(tech: GokyoTechnique, studentBelt: string): boolean {
  const studentOrder = getBeltOrder(studentBelt);
  return tech.minBeltOrder <= studentOrder;
}

